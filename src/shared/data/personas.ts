/**
 * Seed persona library. These named personas are written into the
 * default config on first run (see services/config/envelope.ts ->
 * createDefaultConfig) so a fresh install ships with a few ready-made
 * personas to pick from on the Router page. Existing installs keep
 * whatever Personas they already have on disk — this only fills the
 * brand-new default config.
 *
 * Typed structurally (not via the Persona zod type) to keep this leaf
 * data module free of a schema import cycle.
 */
export interface SeedPersona {
  // Stable uuid key for the persona. Hard-coded (not generated) so a
  // fresh install always seeds the same ids and any reference to them
  // round-trips deterministically.
  id: string
  name: string
  prompt: string
}

